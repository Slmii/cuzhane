export const STRINGS: Record<AppLanguage, Strings> = { tr, en, nl };

export type StringKey = keyof Strings;

/** Replaces `{token}` placeholders. Unknown tokens are left in place so they're obvious in QA. */
export const interpolate = (template: string, values?: Record<string, string | number>) => {
	if (!values) {
		return template;
	}

	return template.replace(/\{(\w+)\}/g, (match, key: string) => {
		const value = values[key];
		return value === undefined ? match : String(value);
	});
};
